    const w = 40, h = 40, cx = (w - 1) / 2, cy = (h - 1) / 2;
    const g = Array.from({ length: h }, () => Array(w).fill('.'));
    for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
      const d = Math.hypot(x - cx, y - cy);
      if (d > 18.2) g[y][x] = '#';
      else if (d > 17.0) g[y][x] = '.';
      else if (d > 8 && d < 12 && (Math.abs(x - cx) < 1.2 || Math.abs(y - cy) < 1.2)) g[y][x] = '#';
      else if (d < 4.5) g[y][x] = 'X';
    }
    return { version: 1, name: 'isle-40x40', width: w, height: h, grid: g.map(r => r.join('')) };
